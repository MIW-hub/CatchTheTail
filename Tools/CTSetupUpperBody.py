import unreal
T = unreal.CTAnimTools
abp = unreal.EditorAssetLibrary.load_asset("/Game/Character/Animation/ABP_CTPlayer")
unreal.log("[CT] ABP 상체 층: " + str(T.add_upper_body_layer(abp, "UpperBody", "Spine", 1)))
unreal.EditorAssetLibrary.save_loaded_asset(abp)
seq = unreal.load_asset("/Game/Character/Animation/Blender/Pull_Heavy_Object")
unreal.log("[CT] 몽타주: " + T.create_hold_throw_montages(seq, "UpperBody", "UpperBodyGroup"))
skel = unreal.load_asset("/Game/Character/Player/Mesh/Chicken_Skeleton")
unreal.EditorAssetLibrary.save_loaded_asset(skel)
hold = unreal.load_asset("/Game/Character/Animation/Blender/AM_Hold_Object_Montage")
throw = unreal.load_asset("/Game/Character/Animation/Blender/AM_Throw_Object_Montage")
unreal.EditorAssetLibrary.save_loaded_asset(hold)
unreal.EditorAssetLibrary.save_loaded_asset(throw)
bp = unreal.load_asset("/Game/Character/Player/BP_CTCharacter")
cdo = unreal.get_default_object(bp.generated_class())
cdo.set_editor_property("HoldMontage", hold)
cdo.set_editor_property("ThrowMontage", throw)
unreal.BlueprintEditorLibrary.compile_blueprint(bp)
unreal.EditorAssetLibrary.save_loaded_asset(bp)
unreal.log("[CT] 캐릭터 BP 연결 완료")
